'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const {_electron:electron}=require(process.env.VINYL_PLAYWRIGHT || 'playwright');
const root=path.resolve(__dirname,'..');
const profile=fs.mkdtempSync(path.join(root,'tmp','floating-chrome-'));
const env={...process.env,VINYL_TEST_PROFILE:profile,VINYL_TEST_WEATHER:'1',VINYL_TEST_GOOGLE_PROFILE:'1'};
delete env.ELECTRON_RUN_AS_NODE;
(async()=>{
 const app=await electron.launch({executablePath:require('electron'),args:[path.join(__dirname,'runtime-fixture.cjs')],env,timeout:25000});
 try {
  const page=await app.firstWindow();
  await page.waitForSelector('#launch-splash',{state:'detached'});
  const dock=app.context().pages().find(p=>p.url().includes('surface=dock'));
  assert.ok(dock,'native floating controls renderer exists');
  const invoke=(name,payload)=>page.evaluate(([name,payload])=>window.vinyl.invoke(name,payload),[name,payload]);
  assert.equal(await page.locator('.tabstrip').isVisible(),false);
  assert.equal((await invoke('app:state')).dockOpen,false);
  await page.mouse.move(300,3);
  await page.waitForTimeout(250);
  assert.equal(await page.locator('.tabstrip').isVisible(),true);
  await page.mouse.move(600,300);
  await page.waitForTimeout(650);
  assert.equal(await page.locator('.tabstrip').isVisible(),false);
  await page.mouse.move(400,877);
  await page.waitForTimeout(250);
  assert.equal((await invoke('app:state')).dockOpen,true);
  await dock.mouse.move(400,35);
  await page.waitForTimeout(1000);
  assert.equal((await invoke('app:state')).dockOpen,true,'hover holds controls open');
  await dock.mouse.move(400,-100);
  await page.mouse.move(600,300);
  await page.waitForTimeout(1100);
  assert.equal((await invoke('app:state')).dockOpen,false,'leaving hides controls after delay');
  await page.keyboard.press('Control+l');
  await dock.waitForFunction(()=>document.activeElement.id==='address');
  assert.equal((await invoke('app:state')).dockOpen,true);
  assert.equal(await dock.locator('#dock-close').count(),0);
  await invoke('browser:navigate',{address:'https://www.youtube.com/'});
  await dock.locator('#address').evaluate(element=>element.blur());
  await dock.waitForSelector('.google-avatar');
  assert.equal(await dock.locator('.google-avatar').getAttribute('src'),'https://yt3.ggpht.com/test-avatar');
  assert.equal(await dock.locator('.google-letter').count(),0);
  await dock.mouse.move(400,35);
  const layers=await app.evaluate(({BrowserWindow})=>{
    const win=BrowserWindow.getAllWindows()[0];
    return {size:win.getContentSize(),children:win.contentView.children.map(v=>({url:v.webContents?.getURL(),bounds:v.getBounds()}))};
  });
  const web=layers.children.find(v=>v.url==='https://www.youtube.com/'),floating=layers.children.find(v=>v.url?.includes('surface=dock'));
  assert.ok(web.bounds.y+web.bounds.height>floating.bounds.y+floating.bounds.height-10,'web page extends behind floating controls');
  assert.ok(layers.children.indexOf(floating)>layers.children.indexOf(web),'controls are composited above the webpage');
  const bounds=await app.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows()[0];w.focus();return w.getContentBounds();});
  // Renderer screenshots omit sibling native views. Capture only the test window.
  const captureScript=`Add-Type -AssemblyName System.Drawing\n$bitmap=New-Object System.Drawing.Bitmap(${bounds.width},${bounds.height})\n$graphics=[System.Drawing.Graphics]::FromImage($bitmap)\n$graphics.CopyFromScreen(${bounds.x},${bounds.y},0,0,$bitmap.Size)\n$bitmap.Save($env:VINYL_SCREENSHOT_PATH,[System.Drawing.Imaging.ImageFormat]::Png)\n$graphics.Dispose()\n$bitmap.Dispose()`;
  execFileSync('powershell.exe',['-NoProfile','-Command',captureScript],{env:{...process.env,VINYL_SCREENSHOT_PATH:path.join(root,'preview-floating-webpage.png')},windowsHide:true});
  await dock.mouse.move(400,-100);
  await page.mouse.move(300,3);
  await page.waitForTimeout(250);
  assert.equal(await page.locator('.tabstrip').isVisible(),true,'top hover works with a live page');
  await page.mouse.move(400,150);
  await page.waitForTimeout(650);
  assert.equal(await page.locator('.tabstrip').isVisible(),false);
  await page.waitForTimeout(1100);
  assert.equal((await invoke('app:state')).dockOpen,false,JSON.stringify(await dock.evaluate(()=>({pointer:ui.dockPointer,focus:document.activeElement.id}))));
  await page.mouse.move(400,877);
  await page.waitForTimeout(200);
  assert.equal((await invoke('app:state')).dockOpen,true,'bottom hover works with a live page');
  await dock.screenshot({path:path.join(root,'preview-floating-dock.png')});
  await page.screenshot({path:path.join(root,'preview-hover-home.png')});
  console.log('Floating chrome checks passed: top hover, delayed bottom hiding, webpage beneath transparent controls, and Google photo extraction.');
 } finally {await app.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
