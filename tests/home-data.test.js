'use strict';
const assert = require('node:assert/strict');
const {parseNewsRss,parseWeather,decodeXml,weatherLabel} = require('../home-data');
assert.equal(decodeXml('A &amp; B &#8212; &lt;example&gt;'),'A & B — <example>');
const news = parseNewsRss(`<rss><channel><item><title><![CDATA[Story &amp; more - The Paper]]></title><link>https://news.google.com/rss/articles/abc</link><source>The Paper</source><pubDate>${new Date().toUTCString()}</pubDate></item><item><title>Invalid</title><link>javascript:alert(1)</link></item></channel></rss>`);
assert.equal(news.length,1);
assert.equal(news[0].title,'Story & more');
assert.equal(weatherLabel(61),'Light rain');
const stories = parseNewsRss('<rss>'+Array.from({length:6},(_,i)=>`<item><title>Story ${i}</title><link>https://www.bbc.com/news/articles/${i}</link><media:thumbnail url="https://ichef.bbci.co.uk/image${i}.jpg"/></item>`).join('')+'</rss>');
assert.equal(stories.length,4);
assert.equal(stories[0].image,'https://ichef.bbci.co.uk/image0.jpg');
assert.equal(parseNewsRss('<item><title>Unsafe image</title><link>https://www.bbc.com/news/one</link><media:thumbnail url="file:///secret"/></item>')[0].image,'');
assert.equal(parseNewsRss('<item><title>Spoof host</title><link>https://www.bbc.com.evil.test/news/one</link></item>').length,0);
const forecast = parseWeather({current:{time:'2026-11-12T13:15',temperature_2m:61.6,weather_code:95,is_day:1},daily:{time:['2026-11-12'],temperature_2m_max:[64.4],temperature_2m_min:[null],weather_code:[95],precipitation_probability_max:[80]},hourly:{time:['2026-11-12T12:00','2026-11-12T13:00','2026-11-12T14:00'],temperature_2m:[60,61,62],weather_code:[3,61,95],is_day:[1,1,1],precipitation_probability:[0,30,80]}},{name:'Test city'});
assert.equal(forecast.temperature,62);
assert.equal(forecast.low,null);
assert.equal(forecast.hourly.length,2);
assert.equal(forecast.hourly[0].time,'2026-11-12T13:00');
assert.equal(forecast.daily[0].rain,80);
assert.throws(()=>parseWeather({current:{temperature_2m:null}},{name:'Test'}),/incomplete/);
console.log('Home feeds parsing passed');
