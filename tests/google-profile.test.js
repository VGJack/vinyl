'use strict';
const assert=require('node:assert/strict');
const {GoogleProfile,profilePage,avatarURL}=require('../google-profile');
(async()=>{
 const picture='https://yt3.ggpht.com/account-photo';
 assert.equal(avatarURL(picture),picture);
 assert.equal(avatarURL('https://lh3.googleusercontent.com/a/photo'),'https://lh3.googleusercontent.com/a/photo');
 for(const url of ['http://yt3.ggpht.com/pic','https://yt3.ggpht.com.attacker.test/pic','javascript:alert(1)','https://user:pass@yt3.ggpht.com/pic','data:image/png;base64,AA','https://random.test/photo'])assert.equal(avatarURL(url),'');
 assert.equal(profilePage('https://www.youtube.com/watch?v=example'),true);
 assert.equal(profilePage('https://myaccount.google.com/'),true);
 assert.equal(profilePage('https://accounts.google.com/AccountChooser'),false,'chooser photos are not the signed-in profile');
 assert.equal(profilePage('https://www.youtube.com.attacker.test/'),false);
 let saves=0,changes=0;
 const store={data:{googleAvatar:picture},save:()=>saves++};
 const profile=new GoogleProfile(store,()=>changes++);
 assert.equal(profile.picture,picture,'last known photo survives restart');
 const wc={getURL:()=> 'https://www.youtube.com/',isDestroyed:()=>false,isLoadingMainFrame:()=>false,executeJavaScriptInIsolatedWorld:async()=>({picture:'https://lh3.googleusercontent.com/a/updated'})};
 await profile.refresh(wc);
 assert.equal(profile.picture,'https://lh3.googleusercontent.com/a/updated');
 assert.equal(saves,1);assert.equal(changes,1);
 await profile.refresh(wc);
 assert.equal(saves,1,'unchanged photo does not repeatedly write the profile');
 wc.executeJavaScriptInIsolatedWorld=async()=>({picture:'https://attacker.test/avatar'});
 await profile.refresh(wc);
 assert.equal(saves,1,'untrusted avatar source is ignored');
 let resolve;
 wc.executeJavaScriptInIsolatedWorld=()=>new Promise(r=>resolve=r);
 const pending=profile.refresh(wc);
 profile.clear();resolve({picture});await pending;
 assert.equal(profile.picture,'','a stale page result cannot restore the photo after sign-out');
 wc.executeJavaScriptInIsolatedWorld=async()=>({picture});await profile.refresh(wc);
 wc.executeJavaScriptInIsolatedWorld=async()=>({signedOut:true});await profile.refresh(wc);
 assert.equal(profile.picture,'');
 wc.getURL=()=> 'https://unrelated.test/';
 wc.executeJavaScriptInIsolatedWorld=()=>{throw new Error('must not inspect unrelated pages');};
 await profile.refresh(wc);
 console.log('Google photo tests passed: trusted account pages/images, persistence, account changes, sign-out and stale navigation results.');
})().catch(error=>{console.error(error);process.exitCode=1;});
